/**
 * Fournit les chaînes **et** le contexte localisé : tous les descendants lisent
 * la bonne langue, y compris via `stringResource(...)`.
 *
 * Le sens de lecture (RTL pour l'arabe) est propagé en même temps que la
 * configuration, pour que la mise en page suive la langue.
 */
@Composable
fun ProvideAppStrings(
    languageCode: String,
    content: @Composable () -> Unit,
) {
    val base = LocalContext.current
    val localized = remember(base, languageCode) { base.localizedTo(languageCode) }
    val strings = remember(localized) { appStrings(localized) }
    val configuration = localized.resources.configuration
    val layoutDirection =
        if (configuration.layoutDirection == View.LAYOUT_DIRECTION_RTL) {
            LayoutDirection.Rtl
        } else {
            LayoutDirection.Ltr
        }
    CompositionLocalProvider(
        LocalContext provides localized,
        LocalConfiguration provides configuration,
        LocalLayoutDirection provides layoutDirection,
        LocalAppStrings provides strings,
        content = content,
    )
}

val LocalAppStrings = staticCompositionLocalOf<AppStrings> {
    error("LocalAppStrings absent : entourer l'écran avec ProvideAppStrings(languageCode) { ... }")
}
