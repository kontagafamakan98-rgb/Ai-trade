/**
 * Langues de l'interface.
 *
 * Aucun drapeau en emoji : un drapeau n'est pas une langue (celui des États-Unis
 * pour l'anglais, du Brésil pour le portugais, d'Arabie saoudite pour l'arabe),
 * et un emoji ne tient pas le rôle d'une icône. Le code (`FR`, `EN`…) dit la
